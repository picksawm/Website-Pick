#!/usr/bin/env node
/**
 * build-wordmark.mjs — the Picksaw mark.
 *
 * A wordmark is not a font. This takes Cormorant Garamond's capitals as
 * raw material and does three things a font cannot:
 *
 *   1. TRACKS BY HAND. Each pair is set individually.
 *
 *   2. CUTS IT. One hairline incision runs across the mark on a shallow
 *      slant — the angle of a blade, not a rule. The gap is real
 *      transparency, so the mark sits on any background.
 *
 *   3. LETS THE FRAGMENT SLIP. The part above the cut is displaced a few
 *      units up and right — a controlled accident, struck and not yet
 *      settled. Legibility is untouched.
 *
 * All geometry is authored in FONT space (y-up, 1000 units/em) and
 * flipped once, so the clip polygons and the letter paths stay in the
 * same coordinate system and cannot drift apart.
 *
 * Output:
 *   public/wordmark.svg                      — the mark, as a file
 *   src/components/brand/wordmark.generated.ts — the same numbers for React
 */
import * as fkN from "fontkit";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const fontkit = fkN.default ?? fkN;
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

const FONT = "node_modules/@fontsource-variable/cormorant-garamond/files/cormorant-garamond-latin-wght-normal.woff2";
const WORD = "PICKSAW";

/* hand tracking, in em — the I needs air, the A and W can take a squeeze */
const TRACK = { P: 0, I: 0.025, C: -0.02, K: -0.012, S: 0.005, A: -0.03, W: -0.018 };

/* the incident */
const CUT_Y = 0.60; // as a share of cap height, measured from the baseline
const SLOPE = -0.038; // rise per unit of run, across the whole mark
const SLIP = { x: 16, y: 26 };

const f = fontkit.openSync(path.join(root, FONT));
const scale = 1000 / f.unitsPerEm;
const cap = f.capHeight * scale;

/* ── set the word ─────────────────────────────────────────────────── */
const run = f.layout(WORD);
let cursor = 0;
const glyphs = [];
for (let i = 0; i < WORD.length; i++) {
  const ch = WORD[i];
  const g = run.glyphs[i];
  const adv = g.advanceWidth * scale;
  glyphs.push({ ch, x: +cursor.toFixed(1), w: +adv.toFixed(1), d: g.path.toSVG({ fontSize: 1000, scale: false }) });
  cursor += adv + (TRACK[ch] ?? 0) * 1000;
}
const width = Math.ceil(cursor);

/* ── the blade ────────────────────────────────────────────────────────
   A line, in font space: y = CUT + SLOPE * (x - width / 2)               */
const CUT = cap * CUT_Y;
const yAt = (x) => CUT + SLOPE * (x - width / 2);

const EXT = 140; // let the blade run past the letters on both sides
const x0 = -EXT;
const x1 = width + EXT;

/* font-space polygons, both covering the glyph area completely */
const abovePts = [
  [x0, yAt(x0)],
  [x1, yAt(x1)],
  [x1, cap + EXT],
  [x0, cap + EXT],
];
const belowPts = [
  [x0, -EXT],
  [x1, -EXT],
  [x1, yAt(x1)],
  [x0, yAt(x0)],
];

const pts = (a) => a.map(([x, y]) => `${x.toFixed(1)},${y.toFixed(1)}`).join(" ");

/* fontkit hands back each glyph in its own space, so the set is only a
   word once each one is translated to the position we tracked. */
const stamps = glyphs.map((g, i) =>
  `    <g transform="translate(${g.x} 0)" ${i === 0 ? 'data-l="P"' : ""}><path d="${g.d}"/></g>`
);
const letters = stamps.join("\n");

/* ── the box ──────────────────────────────────────────────────────────
   Work out the final extent including the slip, then flip once.        */
const PAD = 32;
const topFont = cap + SLIP.y + 6; // tallest point of the slipped fragment
const bottomFont = f.bbox ? Math.min(0, (f.bbox.minY ?? 0) * scale) : 0;

const vbW = width + PAD * 2;
const vbH = topFont - bottomFont + PAD * 2;

/** font space → svg space */
const group = (dx, dy) => `translate(${PAD + dx}, ${PAD + topFont + dy}) scale(1, -1)`;

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${vbW} ${Math.ceil(vbH)}" fill="currentColor" role="img" aria-label="Picksaw">
  <defs>
    <clipPath id="wm-above" clipPathUnits="userSpaceOnUse"><polygon points="${pts(abovePts)}"/></clipPath>
    <clipPath id="wm-below" clipPathUnits="userSpaceOnUse"><polygon points="${pts(belowPts)}"/></clipPath>
  </defs>

  <!-- lower fragment: undisturbed -->
  <g transform="${group(0, 0)}">
    <g clip-path="url(#wm-below)">
${letters}
    </g>
  </g>

  <!-- upper fragment: slipped along the blade -->
  <g transform="${group(SLIP.x, SLIP.y)}">
    <g clip-path="url(#wm-above)">
${letters}
    </g>
  </g>
</svg>
`;

writeFileSync(path.join(root, "public/wordmark.svg"), svg);

/* ── geometry for React, so the inline mark is the same mark ───────── */
const ts = `/* GENERATED by scripts/build-wordmark.mjs — do not edit by hand.
   Source face: Cormorant Garamond capitals, hand-tracked, cut, slipped. */

export const WORDMARK = {
  /** each letter with its own x offset (font units, y-up) */
  letters: ${JSON.stringify(glyphs.map((g) => ({ x: g.x, d: g.d })))},
  /** where the letters are drawn, in the viewBox */
  group: "${group(0, 0)}",
  /** the same, displaced by the slip */
  groupSlipped: "${group(SLIP.x, SLIP.y)}",
  /** the blade, as polygons in font space */
  cut: {
    above: ${JSON.stringify(pts(abovePts))},
    below: ${JSON.stringify(pts(belowPts))},
  },
  viewBox: { w: ${vbW}, h: ${Math.ceil(vbH)} },
  /** cap height as a share of viewBox height — for optical sizing */
  capRatio: ${(cap / vbH).toFixed(4)},
} as const;
`;
writeFileSync(path.join(root, "src/components/brand/wordmark.generated.ts"), ts);

console.log(
  `  ✓ wordmark ${width} units wide · cut ${(CUT_Y * 100).toFixed(0)}% of cap · slip ${SLIP.x},${SLIP.y} · box ${vbW}×${Math.ceil(vbH)}`
);
